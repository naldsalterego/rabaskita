import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import auth from './routes/auth.js';
import destinations from './routes/destinations.js';
import checkin from './routes/checkin.js';
import rewards from './routes/rewards.js';
import admin from './routes/admin.js';
import listings from './routes/listings.js';
import payments, { webhook } from './routes/payments.js';
import bookings from './routes/bookings.js';
import transport from './routes/transport.js';
import owner from './routes/owner.js';
import itineraries from './routes/itineraries.js';
import path from 'node:path';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
const app = express();
app.use(helmet({ contentSecurityPolicy: { directives: { ...helmet.contentSecurityPolicy.getDefaultDirectives(), 'img-src': ["'self'", 'data:', 'https://tile.openstreetmap.org', 'https://*.tile.openstreetmap.org'] } } }), cors({ origin: process.env.CLIENT_ORIGIN }));
app.post('/api/payments/webhook', express.raw({ type: 'application/json' }), webhook);
app.use(express.json({ limit: '1mb' }));
app.use('/api', rateLimit({ windowMs: 60_000, limit: 120 }));
app.use('/api/auth', rateLimit({ windowMs: 15 * 60_000, limit: 30 }), auth);
app.use('/api/destinations', destinations);
app.use('/api/checkin', rateLimit({ windowMs: 60_000, limit: 20 }), checkin);
app.use('/api/rewards', rewards);
app.use('/api/admin', admin);
app.use('/api/payments', payments);
app.use('/api/bookings', bookings);
app.use('/api/transport', transport);
app.use('/api/owner', owner);
app.use('/api/itineraries', itineraries);
app.use('/api', listings);
app.get('/api/health', (_, res) => res.json({ ok: true }));
// Optional single-server deployment: serve the built client when client/dist exists.
const dist = fileURLToPath(new URL('../../client/dist', import.meta.url));
if (fs.existsSync(dist)) { app.use(express.static(dist)); app.get(/^\/(?!api).*/, (_q, res) => res.sendFile(path.join(dist, 'index.html'))); }
app.use((err, _req, res, _next) => { console.error(err); res.status(500).json({ error: 'Something went wrong' }); });
export default app;
